const cls = (s?: string | null) => severityBadge[s || "info"] || severityBadge.info;

const stringifyMaybe = (v: any): string => {
  if (v === null || v === undefined) return "";
  if (typeof v === "string") return v;
  try { return JSON.stringify(v, null, 2); } catch { return String(v); }
};

const buildHttpRequest = (req: any, payload?: string | null): string => {
  if (!req) return "# No request data captured";
  if (typeof req === "string") return req;
  const method = req.method || req.http_method || "GET";
  const url = req.url || req.endpoint || req.path || "/";
  const headers = req.headers || {};
  const body = req.body ?? req.data ?? "";
  const headerLines = Object.entries(headers).map(([k, v]) => `${k}: ${v}`).join("\n");
  const bodyStr = typeof body === "string" ? body : stringifyMaybe(body);
  return `${method} ${url} HTTP/1.1\n${headerLines}${headerLines ? "\n" : ""}${bodyStr ? "\n" + bodyStr : ""}${payload && !bodyStr.includes(payload) ? `\n# Injected payload: ${payload}` : ""}`;
};

const buildHttpResponse = (res: any): string => {
  if (!res) return "# No response data captured";
  if (typeof res === "string") return res;
  const status = res.status || res.status_code || res.statusCode || 200;
  const headers = res.headers || {};
  const body = res.body ?? res.data ?? res.snippet ?? "";
  const headerLines = Object.entries(headers).map(([k, v]) => `${k}: ${v}`).join("\n");
  const bodyStr = typeof body === "string" ? body : stringifyMaybe(body);
  return `HTTP/1.1 ${status}\n${headerLines}${headerLines ? "\n\n" : "\n"}${bodyStr.slice(0, 4000)}`;
};

const generateAdvancedPoc = (f: FindingLike): string => {
  const payload = f.payload || f.payload_used || "<payload>";
  const url = (f.request_data as any)?.url || (f.evidence as any)?.url || `https://${f.target_workspaces?.domain || "target.tld"}/`;
  const method = (f.request_data as any)?.method || "GET";
  const param = f.parameter || (f.evidence as any)?.parameter || "q";
  const escaped = JSON.stringify(payload);

  return `#!/usr/bin/env python3
"""
Advanced Proof-of-Concept — ${f.title}
Severity: ${f.severity?.toUpperCase()} | CVSS: ${f.cvss_score ?? "N/A"}
Generated by CyberScope VAPT (HackerOne-format)

Steps:
  1. Capture baseline response (no payload).
  2. Send mutated request with payload.
  3. Diff status, length, and reflection markers.
  4. Assert deterministic indicator → vulnerability confirmed.
"""
import sys, requests, hashlib, time
from urllib.parse import urlparse, urlencode

TARGET   = ${JSON.stringify(url)}
METHOD   = ${JSON.stringify(method)}
PARAM    = ${JSON.stringify(param)}
PAYLOAD  = ${escaped}
HEADERS  = {"User-Agent": "CyberScope-PoC/1.0"}
TIMEOUT  = 15

def fingerprint(r):
    return {
        "status": r.status_code,
        "len": len(r.text),
        "hash": hashlib.sha1(r.text.encode("utf-8", "ignore")).hexdigest()[:10],
        "reflected": PAYLOAD in r.text,
    }

def send(payload):
    if METHOD.upper() == "GET":
        sep = "&" if "?" in TARGET else "?"
        return requests.get(f"{TARGET}{sep}{urlencode({PARAM: payload})}", headers=HEADERS, timeout=TIMEOUT, allow_redirects=False)
    return requests.request(METHOD, TARGET, data={PARAM: payload}, headers=HEADERS, timeout=TIMEOUT, allow_redirects=False)

def main():
    print(f"[*] Target  : {TARGET}")
    print(f"[*] Vector  : {PARAM} via {METHOD}")
    print(f"[*] Payload : {PAYLOAD!r}\\n")

    print("[*] Step 1 — baseline")
    base = fingerprint(send("cyberscope-baseline-" + str(int(time.time()))))
    print(f"    {base}")

    print("[*] Step 2 — mutated")
    mut = fingerprint(send(PAYLOAD))
    print(f"    {mut}")

    print("\\n[*] Step 3 — differential analysis")
    delta_len = abs(mut["len"] - base["len"])
    pct = (delta_len / max(base["len"], 1)) * 100
    print(f"    Δ status   : {base['status']} → {mut['status']}")
    print(f"    Δ length   : {delta_len} bytes ({pct:.1f}%)")
    print(f"    reflection : {mut['reflected']}")

    confirmed = mut["reflected"] or pct > 25 or base["status"] != mut["status"]
    print("\\n" + ("[+] VULNERABILITY CONFIRMED" if confirmed else "[-] Not reproduced — investigate manually"))
    sys.exit(0 if confirmed else 2)

if __name__ == "__main__":
    main()
`;
};

const buildHackerOneReport = (f: FindingLike): string => {
  const payload = f.payload || f.payload_used || "N/A";
  const target = f.target_workspaces?.name || f.target_workspaces?.domain || "Target";
  const url = (f.request_data as any)?.url || (f.evidence as any)?.url || "N/A";
  const remediation = f.remediation || (f.evidence as any)?.remediation || "Apply input validation, contextual output encoding, and a strict allow-list. Review the affected handler and add WAF rules / parameterized queries as appropriate.";

  return `# ${f.title}

**Target:** ${target}
**Severity:** ${(f.severity || "info").toUpperCase()}
**CVSS:** ${f.cvss_score ?? "N/A"}${f.cvss_vector ? ` (${f.cvss_vector})` : ""}
**Confidence:** ${f.confidence_score ?? 0}% (${f.confidence_level || "n/a"})
${f.cve_ids?.length ? `**Related CVEs:** ${f.cve_ids.join(", ")}\n` : ""}
## Summary
${f.description || "No description provided."}

## Steps to Reproduce
1. Navigate to the affected endpoint:
   \`${url}\`
2. Inject the following payload into parameter \`${f.parameter || "vulnerable_param"}\`:
   \`\`\`
   ${payload}
   \`\`\`
3. Observe the response — see Request/Response evidence below.

## Proof of Concept (HTTP)
**Request**
\`\`\`http
${buildHttpRequest(f.request_data, payload)}
\`\`\`

**Response**
\`\`\`http
${buildHttpResponse(f.response_data || f.mutated_response)}
\`\`\`

## Impact
${(f.evidence as any)?.impact || `An attacker exploiting ${f.title} can compromise the confidentiality, integrity, or availability of the application depending on context (data exfiltration, account takeover, RCE escalation paths).`}

## Remediation
${remediation}

## Triage Reasoning
${f.triage_reasoning || "Pending AI deep-signal triage."}

---
*Generated by CyberScope VAPT — formatted for HackerOne submission.*
`;
};

