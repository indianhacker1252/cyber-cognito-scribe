function drawCoverPage(doc: jsPDF, target: string, total: number, sevCounts: Record<string, number>) {
  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();
  doc.setFillColor(8, 10, 14);
  doc.rect(0, 0, W, H, "F");

  // Diagonal accent
  doc.setFillColor(34, 197, 94);
  doc.triangle(0, 0, 70, 0, 0, 70, "F");
  doc.setFillColor(22, 163, 74);
  doc.triangle(W, H, W - 80, H, W, H - 80, "F");

  doc.setTextColor(34, 197, 94);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.text("CYBERSCOPE", 14, 30);

  doc.setTextColor(240, 240, 240);
  doc.setFontSize(34);
  doc.text("VAPT", 14, 80);
  doc.text("Assessment", 14, 95);
  doc.text("Report", 14, 110);

  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(180, 180, 180);
  doc.text(`Target:  ${target}`, 14, 130);
  doc.text(`Issued:  ${new Date().toLocaleString()}`, 14, 138);
  doc.text(`Findings included: ${total}`, 14, 146);

  // Severity heatmap strip
  doc.setTextColor(140, 140, 140);
  doc.setFontSize(9);
  doc.text("SEVERITY DISTRIBUTION", 14, 168);
  let x = 14;
  const order = ["critical", "high", "medium", "low", "info"];
  for (const s of order) {
    const n = sevCounts[s] || 0;
    const w = Math.max(6, n * 8);
    const c = sevColors[s];
    doc.setFillColor(c[0], c[1], c[2]);
    doc.roundedRect(x, 172, w, 10, 1, 1, "F");
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(8);
    doc.setFont("helvetica", "bold");
    doc.text(`${s[0].toUpperCase()}${n}`, x + w / 2, 178.5, { align: "center" });
    x += w + 2;
  }

  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(120, 120, 120);
  doc.text(
    "This report was generated by CyberScope's autonomous VAPT engine. All findings have been verified through the\n" +
      "triple-verification pipeline (baseline → mutated → re-baseline → replay). Findings flagged 'NEEDS REVIEW' fell below\n" +
      "the auto-confirm threshold and require manual auditor validation prior to disclosure.",
    14,
    H - 32,
  );
  doc.setTextColor(34, 197, 94);
  doc.setFontSize(9);
  doc.text("CONFIDENTIAL — distribute only to authorized stakeholders.", 14, H - 14);
}

function drawExecutiveSummary(
  doc: jsPDF,
  target: string,
  reportFindings: Finding[],
  sevCounts: Record<string, number>,
  statusCounts: Record<string, number>,
) {
  doc.addPage();
  addHeader(doc, target);
  let y = 32;
  doc.setTextColor(20, 20, 20);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("Executive Summary", 14, y);
  y += 9;

  const total = reportFindings.length;
  const crit = sevCounts["critical"] || 0;
  const high = sevCounts["high"] || 0;
  const exploited = reportFindings.filter(f => f.proof_tier === "exploited").length;
  const confirmed = statusCounts["confirmed"] || 0;
  const verdict =
    crit > 0 ? "CRITICAL" : high > 0 ? "HIGH RISK" : total > 0 ? "MODERATE" : "LOW RISK";
  const verdictColor: [number, number, number] =
    verdict === "CRITICAL" ? [220, 38, 38]
      : verdict === "HIGH RISK" ? [234, 88, 12]
        : verdict === "MODERATE" ? [217, 119, 6]
          : [22, 163, 74];

  doc.setFillColor(verdictColor[0], verdictColor[1], verdictColor[2]);
  doc.roundedRect(14, y, 60, 9, 1.5, 1.5, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(11);
  doc.text(`OVERALL POSTURE: ${verdict}`, 17, y + 6);
  y += 16;

  doc.setTextColor(40, 40, 40);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  const summary =
    `CyberScope assessed ${target} and surfaced ${total} verified finding${total === 1 ? "" : "s"}. ` +
    `Of these, ${crit} are critical and ${high} are high severity. ` +
    `${exploited} finding${exploited === 1 ? " was" : "s were"} promoted to the highest 'EXPLOITED' proof tier via deterministic ` +
    `proof-of-concept execution. ${confirmed} finding${confirmed === 1 ? "" : "s"} passed the automated triple-verification gate; ` +
    `the remainder are flagged for auditor review. Address critical items before any production deploy.`;
  const sLines = doc.splitTextToSize(summary, 180);
  doc.text(sLines, 14, y);
  y += sLines.length * 5 + 6;

  // Top findings table
  autoTable(doc, {
    startY: y,
    head: [["#", "Severity", "Title", "OWASP", "CVSS"]],
    body: reportFindings.slice(0, 10).map((f, i) => {
      const tags = classifyFinding(f.finding_type || f.title);
      const cvss = deriveCvssVector(f.severity, f.cvss_score);
      return [String(i + 1), (f.severity || "info").toUpperCase(), f.title.slice(0, 60), tags.owasp, String(cvss.score)];
    }),
    headStyles: { fillColor: [22, 22, 26], textColor: [34, 197, 94] },
    styles: { fontSize: 8, cellPadding: 1.5 },
    columnStyles: { 0: { cellWidth: 8 }, 1: { cellWidth: 18 }, 4: { cellWidth: 14 } },
  });
}

// ──────────────────────────────────────────────────────────────────────────────
// Single-finding PDF (kept lightweight, plus CVSS / OWASP enrichment)
// ──────────────────────────────────────────────────────────────────────────────

export async function generateFindingPdf(f: Finding) {
  const ep = await fetchEndpoint(f.endpoint_id);
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const target = f.target_workspaces?.name || f.target_workspaces?.domain || "Target";
  const tags = classifyFinding(f.finding_type || f.title);
  const cvss = deriveCvssVector(f.severity, f.cvss_score);
  addHeader(doc, target);

  let y = 32;
  doc.setTextColor(20, 20, 20);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text(f.title, 14, y);
  y += 8;

  severityBox(doc, f.severity || "info", 14, y);
  doc.setTextColor(60, 60, 60);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text(`CVSS ${cvss.score}  •  Confidence ${f.confidence_score ?? 0}%  •  ${(f.validation_status ?? "unverified").toUpperCase()}`, 40, y - 1);
  y += 8;

  autoTable(doc, {
    startY: y,
    theme: "grid",
    headStyles: { fillColor: [22, 22, 26], textColor: [34, 197, 94] },
    styles: { fontSize: 9, cellPadding: 2 },
    body: [
      ["Finding ID", f.id],
      ["Target", target],
      ["Affected Endpoint", ep ? `${ep.method} ${ep.url}` : "—"],
      ["OWASP Top 10", tags.owasp],
      ["CWE", `${tags.cwe} — ${tags.cwe_name}`],
      ["CVSS 3.1", cvss.vector],
      ["Proof Tier", (f.proof_tier ?? "signal").toUpperCase()],
      ["Discovered", new Date(f.created_at).toLocaleString()],
    ],
  });
  y = (doc as any).lastAutoTable.finalY + 6;

  const section = (title: string, body: string) => {
    if (y > 260) { doc.addPage(); addHeader(doc, target); y = 32; }
    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    doc.setTextColor(34, 197, 94);
    doc.text(title, 14, y);
    y += 5;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(40, 40, 40);
    const lines = doc.splitTextToSize(body || "—", 180);
    doc.text(lines, 14, y);
    y += lines.length * 4 + 4;
  };

  section("DESCRIPTION", f.description || "No description provided.");
  const steps = reproSteps(ep?.method || "GET", ep?.url || "", f.payload, undefined);
  section("REPRODUCTION STEPS", steps.map((s, i) => `${i + 1}. ${s}`).join("\n"));
  section("PROOF OF CONCEPT", f.poc || f.payload || "No PoC recorded.");
  section("AI TRIAGE REASONING", f.triage_reasoning || "—");
  section("REMEDIATION", f.remediation || "Apply input validation, parameterized queries, output encoding, and follow OWASP guidelines for this vulnerability class. Validate the patch with regression tests before deploying to production.");
  section("IMPACT", `A successful exploit of "${f.title}" maps to ${tags.owasp} (${tags.cwe}). Severity ${f.severity?.toUpperCase()} — CVSS base ${cvss.score}. Treat ${f.proof_tier === "exploited" ? "as a confirmed compromise vector" : "as a likely-real defect pending manual verification"}.`);

  addFooter(doc);
  doc.save(`cyberscope-${f.id.slice(0, 8)}-${(f.title || "finding").replace(/[^a-z0-9]+/gi, "-").slice(0, 40)}.pdf`);
}

// ──────────────────────────────────────────────────────────────────────────────
// Bulk auditor-grade report
// ──────────────────────────────────────────────────────────────────────────────

export async function generateBulkPdf(
  findings: Finding[],
  targetName: string,
  opts: { includeNeedsReview?: boolean } = {},
) {
  const includeNeedsReview = opts.includeNeedsReview !== false;
  const allowed = new Set(includeNeedsReview ? ["confirmed", "needs_review"] : ["confirmed"]);
  const reportFindings = findings.filter(f => allowed.has((f.validation_status || "").toLowerCase()));
  const excludedCount = findings.length - reportFindings.length;

  const sevCounts = reportFindings.reduce<Record<string, number>>((a, f) => { a[f.severity] = (a[f.severity] || 0) + 1; return a; }, {});
  const statusCounts = reportFindings.reduce<Record<string, number>>((a, f) => {
    const s = (f.validation_status || "unverified").toLowerCase();
    a[s] = (a[s] || 0) + 1; return a;
  }, {});

  const doc = new jsPDF({ unit: "mm", format: "a4" });

  // 1. Cover
  drawCoverPage(doc, targetName, reportFindings.length, sevCounts);

  // 2. Executive summary + top-10 table
  drawExecutiveSummary(doc, targetName, reportFindings, sevCounts, statusCounts);

  // 3. Compliance + scope page
  doc.addPage();
  addHeader(doc, targetName);
  doc.setTextColor(20, 20, 20);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text("Compliance Mapping", 14, 36);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(60, 60, 60);
  doc.text("Findings grouped by OWASP Top 10 (2021) category and CWE.", 14, 44);

  const owaspGroups = reportFindings.reduce<Record<string, number>>((a, f) => {
    const tags = classifyFinding(f.finding_type || f.title);
    a[tags.owasp] = (a[tags.owasp] || 0) + 1;
    return a;
  }, {});
  autoTable(doc, {
    startY: 52,
    head: [["OWASP Top 10 (2021)", "Findings"]],
    body: Object.entries(owaspGroups).sort((a, b) => b[1] - a[1]).map(([k, v]) => [k, String(v)]),
    headStyles: { fillColor: [22, 22, 26], textColor: [34, 197, 94] },
    styles: { fontSize: 9, cellPadding: 2 },
  });

  if (excludedCount > 0) {
    const finalY = (doc as any).lastAutoTable.finalY + 8;
    doc.setTextColor(140, 140, 140);
    doc.setFontSize(9);
    doc.text(
      `${excludedCount} inconclusive finding${excludedCount === 1 ? "" : "s"} excluded by the triple-verification gate (low confidence).`,
      14,
      finalY,
    );
  }

  if (reportFindings.length === 0) {
    doc.addPage();
    addHeader(doc, targetName);
    doc.setFontSize(14);
    doc.setTextColor(60, 60, 60);
    doc.text("No findings passed the triple-verification gate.", 14, 50);
    doc.setFontSize(10);
    doc.text("Re-Verify candidate findings or lower the inclusion threshold to populate this report.", 14, 60);
    addFooter(doc);
    doc.save(`cyberscope-vapt-${targetName.replace(/[^a-z0-9]+/gi, "-")}-${Date.now()}.pdf`);
    return;
  }

  const statusPill = (doc: jsPDF, status: string, x: number, y: number) => {
    const conf = status === "confirmed";
    const c: [number, number, number] = conf ? [22, 163, 74] : [217, 119, 6];
    const label = conf ? "CONFIRMED" : "NEEDS REVIEW";
    doc.setFillColor(c[0], c[1], c[2]);
    doc.roundedRect(x, y - 5, 32, 6, 1, 1, "F");
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(8);
    doc.setFont("helvetica", "bold");
    doc.text(label, x + 16, y - 1, { align: "center" });
  };

  // 4. Per-finding detail pages
  for (const f of reportFindings) {
    const tags = classifyFinding(f.finding_type || f.title);
    const cvss = deriveCvssVector(f.severity, f.cvss_score);
    doc.addPage();
    addHeader(doc, targetName);
    let y = 32;
    doc.setTextColor(20, 20, 20);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(14);
    doc.text(f.title, 14, y);
    y += 7;
    severityBox(doc, f.severity || "info", 14, y);
    statusPill(doc, (f.validation_status || "needs_review").toLowerCase(), 40, y);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(60, 60, 60);
    doc.text(`CVSS ${cvss.score}  •  Confidence ${f.confidence_score ?? 0}%  •  ${tags.owasp}`, 76, y - 1);
    y += 6;

    const ep = await fetchEndpoint(f.endpoint_id);
    const block = (label: string, txt: string) => {
      if (y > 260) { doc.addPage(); addHeader(doc, targetName); y = 32; }
      doc.setFont("helvetica", "bold"); doc.setFontSize(10); doc.setTextColor(34, 197, 94);
      doc.text(label, 14, y); y += 4;
      doc.setFont("helvetica", "normal"); doc.setFontSize(9); doc.setTextColor(40, 40, 40);
      const lines = doc.splitTextToSize(txt || "—", 180);
      doc.text(lines, 14, y); y += lines.length * 4 + 3;
    };

    block("Endpoint", ep ? `${ep.method} ${ep.url}` : "—");
    block("Compliance", `${tags.owasp}  •  ${tags.cwe} — ${tags.cwe_name}`);
    block("CVSS 3.1 Vector", cvss.vector);

    if ((f.validation_status || "").toLowerCase() === "needs_review") {
      block("⚠ Why flagged for review", f.triage_reasoning || "Confidence below auto-confirm threshold (95%). Manual auditor verification recommended.");
    } else {
      block("Verification", f.triage_reasoning || "Triple-verification passed (baseline → mutated → rebaseline → replay).");
    }
    block("Description", f.description || "—");

    const steps = reproSteps(ep?.method || "GET", ep?.url || "", f.payload, undefined);
    block("Reproduction Steps", steps.map((s, i) => `${i + 1}. ${s}`).join("\n"));

    block("Proof of Concept", f.poc || f.payload || "—");
    block(
      "Impact",
      `Maps to ${tags.owasp} (${tags.cwe}). ${
        f.proof_tier === "exploited"
          ? "Confirmed exploitable — treat as an active compromise vector."
          : "Likely-real defect pending manual verification — auditor must validate before disclosure."
      }`,
    );
    block("Remediation", f.remediation || "Apply standard OWASP remediation guidance for this vulnerability class.");
  }

  addFooter(doc);
  doc.save(`cyberscope-vapt-${targetName.replace(/[^a-z0-9]+/gi, "-")}-${Date.now()}.pdf`);
}
